const {readFileSync}=require('node:fs');
const path=require('node:path');
const ts=require('typescript');
const assert=require('node:assert/strict');
const cache=new Map();
function load(name){
  const file=path.resolve(__dirname,'..',name);
  if(cache.has(file))return cache.get(file).exports;
  const m={exports:{}};cache.set(file,m);
  const code=ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
  new Function('require','module','exports',code)((s)=>s.startsWith('.')?load(path.relative(path.resolve(__dirname,'..'),path.resolve(path.dirname(file),s+'.ts'))):require(s),m,m.exports);
  return m.exports;
}
const {buildDraft,validateSquad,evaluatePlan,withPlayers}=load('lib/transfer-planner.ts');
const {projectPlayer}=load('lib/fpl-analysis.ts');
const events=[1,2,3,4,5,6].map(id=>({id,deadline_time:`2099-01-${String(id+10).padStart(2,'0')}T12:00:00Z`,is_next:id===1}));
const teams=Array.from({length:10},(_,i)=>({id:i+1,name:`Club ${i+1}`,short_name:`T${i+1}`}));
const players=teams.flatMap(t=>[1,2,3,4].flatMap(pos=>[0,1].map(n=>({id:t.id*100+pos*10+n,team:t.id,element_type:pos,web_name:`P${t.id}-${pos}-${n}`,now_cost:40+n*10+t.id,minutes:900,form:String(2+n+t.id/10),ep_next:'5',points_per_game:'4',status:'a',chance_of_playing_next_round:100,selected_by_percent:'5',total_points:40,cost_change_event:0}))));
const fixtures=events.flatMap(e=>[1,3,5,7,9].map(t=>({event:e.id,team_h:t,team_a:t+1,team_h_difficulty:3,team_a_difficulty:3})));
const data={events,teams,players,fixtures};
const draft=buildDraft(data,events,1000,'balanced');
assert.equal(draft.error,'');assert.equal(draft.players.length,15);
assert.equal(validateSquad(draft.players,1000-draft.players.reduce((s,p)=>s+p.now_cost,0)),'');
assert.ok(buildDraft(data,events,10,'balanced').error);
assert.ok(buildDraft(data,events,NaN,'balanced').error);
const squad=withPlayers({usedChips:[],picks:[],bank:100},draft.players,100);
const roll=evaluatePlan(data,squad,events,[],1);
assert.equal(roll.error,'');assert.equal(roll.rows[0].free,2);assert.equal(roll.rows[5].free,5);
assert.ok(roll.rows.every(r=>r.hit===0&&r.points===r.baseline));
const out=draft.players[0];
const incoming=players.find(p=>p.element_type===out.element_type&&!squad.playerIds.includes(p.id)&&draft.players.filter(q=>q.team===p.team&&q.id!==out.id).length<3);
const move={event:1,out:out.id,in:incoming.id,sellPrice:out.now_cost};
const paid=evaluatePlan(data,squad,events,[move],0);
assert.equal(paid.error,'');assert.equal(paid.rows[0].hit,4);assert.equal(paid.rows[1].hit,0);
assert.equal(paid.rows[0].bank,100+out.now_cost-incoming.now_cost);
assert.ok(evaluatePlan(data,squad,events,[{...move,in:draft.players[1].id}],1).error);
assert.ok(evaluatePlan(data,squad,events,[{...move,sellPrice:out.now_cost+1}],1).error);
assert.ok(evaluatePlan(data,squad,events,[{...move,event:99}],1).error);
assert.ok(evaluatePlan(data,squad,events,[null],1).error);
assert.ok(evaluatePlan(data,squad,events,[],NaN).error);
assert.equal(projectPlayer(players[0],events[1],data).points,projectPlayer({...players[0],ep_next:'20'},events[1],data).points);
assert.equal(projectPlayer({...players[0],chance_of_playing_next_round:0},events[0],data).points,0);
console.log('Planner checks passed: legal drafts, budget limits, duplicate rejection, hit costs, free-transfer rollover and future projections.');
